// tests/auth.test.ts
import { assertEquals, assertExists, assertFalse } from "@std/assert";
import { app } from "../src/app.ts";
import { setupTestDB, teardownTestDB } from "./setup.ts";
import { ApiStatus } from "../src/api_status.ts";

Deno.test({
  name: "Auth API Integration Tests (Refactored)",
  async fn(t) {
    await setupTestDB();

    const testUser = {
      email: "test_refactored@example.com",
      password: "securepassword123",
    };

    await t.step("POST /api/v1/auth/register - Successfully creates a user", async () => {
      const req = new Request("http://localhost/api/v1/auth/register", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(testUser),
      });

      const res = await app.request(req);
      const payload = await res.json();

      assertEquals(res.status, ApiStatus.CREATED.httpCode);
      assertEquals(payload.success, true);
      assertEquals(payload.code, ApiStatus.CREATED.code);
      
      assertExists(payload.data);
      assertExists(payload.data.access_token);
      assertExists(payload.data.refresh_token);
      assertEquals(payload.data.user.email, testUser.email);
      assertEquals(payload.data.user.onboardingStep, "identity");
    });

    await t.step("POST /api/v1/auth/register - Fails when email is already taken", async () => {
      const req = new Request("http://localhost/api/v1/auth/register", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(testUser), // Sending the exact same email
      });

      const res = await app.request(req);
      const payload = await res.json();

      assertEquals(res.status, ApiStatus.BAD_REQUEST.httpCode);
      assertFalse(payload.success);
      assertEquals(payload.code, ApiStatus.BAD_REQUEST.code);
      assertEquals(payload.message, "BAD_REQUEST");
      
      // Validating the custom data payload generated by the controller's DUPLICATE_USER catch block
      assertExists(payload.data);
      assertEquals(payload.data.message, "This email is already registered.");
    });

    await t.step("POST /api/v1/auth/login - Fails with unregistered email", async () => {
      const req = new Request("http://localhost/api/v1/auth/login", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          email: "nobody@example.com",
          password: "securepassword123",
        }),
      });

      const res = await app.request(req);
      const payload = await res.json();

      // Controller returns AUTH_USER_NOT_FOUND when the DB lookup fails
      assertEquals(res.status, ApiStatus.AUTH_USER_NOT_FOUND.httpCode);
      assertFalse(payload.success);
      assertEquals(payload.code, ApiStatus.AUTH_USER_NOT_FOUND.code);
      assertEquals(payload.message, "AUTH_USER_NOT_FOUND");
    });

    await t.step("POST /api/v1/auth/login - Fails with incorrect password", async () => {
      const req = new Request("http://localhost/api/v1/auth/login", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          email: testUser.email,
          password: "wrongpassword",
        }),
      });

      const res = await app.request(req);
      const payload = await res.json();

      // Controller returns AUTH_USER_NOT_FOUND when verifyPassword fails
      assertEquals(res.status, ApiStatus.AUTH_USER_NOT_FOUND.httpCode);
      assertFalse(payload.success);
      assertEquals(payload.code, ApiStatus.AUTH_USER_NOT_FOUND.code);
      assertEquals(payload.message, "AUTH_USER_NOT_FOUND");
    });

    await t.step("POST /api/v1/auth/login - Successfully logs in", async () => {
      const req = new Request("http://localhost/api/v1/auth/login", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(testUser),
      });

      const res = await app.request(req);
      const payload = await res.json();

      assertEquals(res.status, ApiStatus.OK.httpCode);
      assertEquals(payload.success, true);
      assertEquals(payload.code, ApiStatus.OK.code);
      assertExists(payload.data.access_token);
      assertExists(payload.data.refresh_token);
      assertEquals(payload.data.user.email, testUser.email);
    });

    await teardownTestDB();
  },
  sanitizeOps: false,
  sanitizeResources: false,
});